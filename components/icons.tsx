// Ikon garis berbasis Lucide (https://lucide.dev, lisensi ISC), disalin sebagai SVG inline
// supaya tidak perlu dependency. Satu tebal garis (1.75) untuk semua; ukuran 16 atau 20.
// Semua dekoratif -> aria-hidden (label ada di teks/aria-label tombolnya).
type IconProps = { size?: 16 | 20; className?: string };

function Svg({ size = 20, className, children }: IconProps & { children: React.ReactNode }) {
  return (
    <svg
      aria-hidden="true"
      width={size}
      height={size}
      viewBox="0 0 24 24"
      fill="none"
      stroke="currentColor"
      strokeWidth={1.75}
      strokeLinecap="round"
      strokeLinejoin="round"
      className={`shrink-0 ${className ?? ''}`}
    >
      {children}
    </svg>
  );
}

